#Pre-pandemic
rm(list=ls())
pacman::p_load(dplyr, readr, data.table, lubridate, stringr, janitor)

setwd('C:/Data/Shared Folder/People/Rubyath/Data/Master files')
guess_encoding("ari cases_age_sex_migration background.csv")
demographics <- read.csv("ari cases_age_sex_migration background.csv")
setwd('C:/Data/Shared Folder/People/Rubyath/Data/Working files/Intermediate data/Period 1')
guess_encoding("care_chain_diag_period1.csv")
episode_p1 <- read_csv2("care_chain_diag_period1.csv")
problem_columns <- sapply(episode_p1, function(col) {if(is.character(col) || is.factor(col)) {any(!validUTF8(as.character(col)), na.rm = TRUE)} else {FALSE}})
episode_p1$inrattning_name <- iconv(episode_p1$inrattning_name, from = "latin1", to = "UTF-8")
episode_p1$first_admission_year <- year(episode_p1$first_admission_datetime)
if_null <- sum(is.null(episode_p1$first_admission_year))
rm(if_null)
episode_p1_demo <- left_join(episode_p1, demographics, by = c ("lopnr.x" = "lopnr"))
View(episode_p1_demo)
rm(episode_p1)
colSums(is.na(demographics))
colSums(is.na(episode_p1_demo))
#missing_birth_year <- episode_p1_demo %>% filter(is.na(fodelsear))
#missing_birth_year <- unique(missing_birth_year$lopnr.x)
episode_p1_demo <- episode_p1_demo %>% mutate(age_year = first_admission_year - fodelsear)
episode_p1_demo <- episode_p1_demo %>% filter(age_year >= 18)
fwrite(episode_p1_demo, file= "final_cc1_demo.csv", sep = ";", quote = TRUE, bom = TRUE)


